import { test, expect } from "@playwright/test";

test("owner can enter a synthetic reviewed structure draft", async ({ page }) => {
  await page.goto("/admin");
  await page.getByLabel("Email", { exact: true }).fill("owner@example.invalid");
  await page.getByLabel("Password", { exact: true }).fill("Synthetic-test-only-927156!");
  await page.getByRole("button", { name: "Sign in", exact: true }).click();
  await page.getByRole("button", { name: "Content", exact: true }).click();
  const editor = page.locator("details.admin-card").filter({ hasText: "Add content" });
  await editor.locator(":scope > summary").click();
  await editor.getByRole("combobox", { name: "Kind", exact: true }).selectOption("structure");
  await expect(editor.getByLabel("Footprint WGS84 coordinates")).toBeVisible();
  await expect(editor.getByLabel("Physical anchor latitude")).toBeVisible();
  await expect(editor.getByLabel("Model pivot right (m)")).toBeVisible();
  await expect(editor.getByLabel("Measured height (m, optional)")).toBeVisible();
  await editor.getByLabel("Content ID").fill("synthetic-building");
  await editor.getByLabel("Name (English)").fill("Synthetic building");
  await editor.getByLabel("Footprint WGS84 coordinates").fill(JSON.stringify({ outer: [[74.909,24.467],[74.90915,24.467],[74.90915,24.46704],[74.90908,24.46704],[74.90908,24.4671],[74.909,24.4671],[74.909,24.467]], holes: [] }));
  await editor.getByRole("button", { name: "Apply footprint coordinates" }).click();
  await editor.getByLabel("Footprint source", { exact: true }).fill("Synthetic fixture evidence");
  await editor.getByLabel("Footprint source revision").fill("fixture-1");
  await editor.getByLabel("Physical anchor latitude").fill("24.467");
  await editor.getByLabel("Physical anchor longitude").fill("74.909");
  await editor.getByLabel("Bearing clockwise from north (degrees)").fill("30");
  await editor.getByLabel("Measured height (m, optional)").fill("4");
  await editor.getByLabel("Height source", { exact: true }).fill("Synthetic height evidence");
  await editor.getByLabel("Height source revision").fill("height-1");
  await editor.getByLabel("Last reviewed (ISO date/time)").fill("2026-01-01T00:00:00Z");
  await editor.getByLabel("Visible to customers after publication").check();
  await editor.getByLabel("Reason", { exact: true }).fill("Synthetic structure staging");
  await editor.getByRole("button", { name: "Save content" }).click();
  await expect(page.locator("details.admin-card > summary").filter({ hasText: "synthetic-building · Draft" })).toBeVisible();
  await page.reload();
  await page.getByRole("button", { name: "Content", exact: true }).click();
  const saved = page.locator("details.admin-card").filter({ hasText: "synthetic-building" });
  await saved.locator(":scope > summary").click();
  await expect(saved.getByLabel("Measured height (m, optional)")).toHaveValue("4");
  await saved.getByLabel("Reason", { exact: true }).fill("Synthetic structure review");
  await saved.getByLabel("Publish after evidence verification").check();
  await saved.getByRole("button", { name: "Save content" }).click();
  await expect(page.locator("details.admin-card > summary").filter({ hasText: "synthetic-building · Published" })).toBeVisible();
  const publicHeight = async () => {
    const project = await (await page.request.get("/api/public/project")).json();
    return project.items.find((item) => item.id === "synthetic-building")?.published.height?.metres;
  };
  await expect.poll(publicHeight).toBe(4);
  await page.reload();
  await page.getByRole("button", { name: "Content", exact: true }).click();
  const revision = page.locator("details.admin-card").filter({ hasText: "synthetic-building" });
  await revision.locator(":scope > summary").click();
  await revision.getByLabel("Measured height (m, optional)").fill("6");
  await revision.getByLabel("Reason", { exact: true }).fill("Synthetic revised height evidence");
  await revision.getByRole("button", { name: "Save content" }).click();
  await expect.poll(async () => {
    const data = await (await page.request.get("/api/admin/content")).json();
    return data.items.find((item) => item.id === "synthetic-building")?.draft.height?.metres;
  }).toBe(6);
  expect(await publicHeight()).toBe(4);
  await page.reload();
  await page.getByRole("button", { name: "Content", exact: true }).click();
  await revision.locator(":scope > summary").click();
  await expect(revision.getByLabel("Measured height (m, optional)")).toHaveValue("6");
  await revision.getByLabel("Reason", { exact: true }).fill("Synthetic superseding review");
  await revision.getByLabel("Publish after evidence verification").check();
  await revision.getByRole("button", { name: "Save content" }).click();
  await expect.poll(publicHeight).toBe(6);
  await page.goto("/explore");
  await page.getByRole("button", { name: "2D plan (Source drawing)" }).click();
  await expect(page.locator('[data-structure-id="synthetic-building"]')).toBeVisible();
  await page.getByRole("button", { name: "Synthetic building", exact: true }).click();
  await page.getByRole("button", { name: "3D colony" }).click();
  await expect(page.getByRole("button", { name: "Synthetic building", exact: true })).toHaveAttribute("aria-pressed", "true");
  await expect(page.locator(".colony-three-view canvas")).toBeVisible();
  await page.goto("/admin");
  await page.getByRole("button", { name: "Content", exact: true }).click();
  await revision.locator(":scope > summary").click();
  await revision.getByLabel("Reason", { exact: true }).fill("Synthetic withdrawal review");
  await revision.getByRole("button", { name: "Unpublish structure" }).click();
  await expect.poll(publicHeight).toBeUndefined();
});
