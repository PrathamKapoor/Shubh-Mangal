import { test, expect } from "@playwright/test";
test("synthetic site customer and owner paths do not show original site sources", async ({ page }) => {
  const legacyRequests = [];
  page.on("request", request => { if (/geographic-layout|survey-plan-north|colony-poster|Shubh_Mangal_Full_Layout/.test(request.url())) legacyRequests.push(request.url()); });
  await page.goto("/");
  await expect(page.getByRole("link", { name: "Synthetic Harbour Gardens home" })).toBeVisible();
  await expect(page.locator(".hero-plan img")).toHaveAttribute("src", "/synthetic/schematic.svg");
  expect((await page.request.get("/synthetic/schematic.svg")).status()).toBe(200);
  await page.goto("/documents");
  await expect(page.getByText("North-oriented survey plan")).toHaveCount(0);
  await expect(page.getByText("Marketing poster")).toHaveCount(0);
  await page.goto("/explore");
  await expect(page.getByRole("button", { name: "Original plan", exact: true })).toHaveCount(0);
  await expect(page.locator("body")).not.toContainText("SHUBH MANGAL");
  await expect(page.locator("[data-illustrative-road-details]")).toHaveCount(0);
  await page.goto("/admin");
  await page.getByLabel("Email", { exact: true }).fill("siteb@example.invalid");
  await page.getByLabel("Password", { exact: true }).fill("Synthetic-test-only-927156!");
  await page.getByRole("button", { name: "Sign in", exact: true }).click();
  await expect(page.getByText("Synthetic Harbour Gardens · OWNER WORKSPACE")).toBeVisible();
  await page.getByRole("button", { name: "Content", exact: true }).click();
  await expect(page.getByRole("button", { name: "Stage owner-indicated amenities" })).toHaveCount(0);
  expect(legacyRequests).toEqual([]);
});
test("synthetic build cannot fall back to the original site while offline", async ({ page }) => {
  const requests = [];
  page.on("request", r => requests.push(r.url()));
  await page.route("**/api/**", route => route.abort());
  await page.goto("/explore");
  await expect(page.getByRole("link", { name: "Synthetic Harbour Gardens home" })).toBeVisible();
  await expect(page.locator("body")).not.toContainText("SHUBH MANGAL");
  await expect(page.getByRole("heading", { name: "Unable to load the drawing" })).toBeVisible();
  expect(requests.filter(url => /\/data\/layout\.json|geographic-layout|survey-plan-north|colony-poster/.test(url))).toEqual([]);
});
